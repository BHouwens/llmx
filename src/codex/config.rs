//! Generating codex-local configuration.
//!
//! Every key emitted here was checked against the codex-local source in this
//! repository, not against its README:
//!
//! * `model`, `model_provider`, `model_context_window`, `model_max_output_tokens`,
//!   `model_auto_compact_token_limit` — `codex-rs/core/src/config.rs`, `ConfigToml`.
//! * `[model_providers.<id>]` fields — `codex-rs/core/src/model_provider_info.rs`,
//!   `ModelProviderInfo`.
//! * `wire_api` accepts exactly `"chat"` and `"responses"` (lowercase) —
//!   same file, `enum WireApi`.
//! * `requires_openai_auth = false` is what keeps codex-local from showing a
//!   login screen for a provider that has no OpenAI account behind it —
//!   `codex-rs/tui/src/lib.rs`, `should_show_login_screen`.
//!
//! Nothing outside that set is invented.

use crate::backend::ModelEndpoint;
use crate::config::ModelProfile;
use anyhow::anyhow;
use anyhow::Result;
use std::path::Path;
use std::path::PathBuf;
use toml::value::Table;
use toml::Value;

/// Provider key used inside the generated config. Namespaced by profile id so
/// it cannot collide with a provider the user defined themselves.
pub fn provider_key(profile_id: &str) -> String {
    format!("llmx-{profile_id}")
}

/// Build the codex-local configuration document for one resolved endpoint.
pub fn build_document(profile: &ModelProfile, endpoint: &ModelEndpoint) -> Table {
    let key = provider_key(&profile.id);

    let mut provider = Table::new();
    provider.insert(
        "name".to_string(),
        Value::String(format!("llmx: {}", profile.name)),
    );
    provider.insert(
        "base_url".to_string(),
        Value::String(endpoint.base_url.clone()),
    );
    provider.insert(
        "wire_api".to_string(),
        Value::String(profile.wire_api.as_str().to_string()),
    );
    // Local and tunnelled servers stream slowly while loading context; the
    // codex default of 300s is right, but stating it makes the generated file
    // self-describing.
    provider.insert(
        "stream_idle_timeout_ms".to_string(),
        Value::Integer(300_000),
    );
    provider.insert("request_max_retries".to_string(), Value::Integer(2));
    provider.insert("stream_max_retries".to_string(), Value::Integer(2));
    // Without this, codex-local shows its OpenAI login screen before the
    // session starts.
    provider.insert("requires_openai_auth".to_string(), Value::Boolean(false));

    // Only the *name* of the variable is written. llmx never puts key
    // material in a file it generates; codex-local reads the variable itself.
    if let Some(env_key) = &profile.endpoint.env_key {
        provider.insert("env_key".to_string(), Value::String(env_key.clone()));
    }

    let mut providers = Table::new();
    providers.insert(key.clone(), Value::Table(provider));

    let mut doc = Table::new();
    doc.insert(
        "model".to_string(),
        Value::String(endpoint.model_id.clone()),
    );
    doc.insert("model_provider".to_string(), Value::String(key));

    if let Some(ctx) = endpoint.context_window {
        doc.insert(
            "model_context_window".to_string(),
            Value::Integer(ctx as i64),
        );
    }
    if let Some(max_out) = endpoint.max_output_tokens {
        doc.insert(
            "model_max_output_tokens".to_string(),
            Value::Integer(max_out as i64),
        );
    }
    if let Some(limit) = profile.auto_compact_token_limit {
        doc.insert(
            "model_auto_compact_token_limit".to_string(),
            Value::Integer(limit),
        );
    }

    // Profile passthrough last, so a user can override anything above.
    for (key, value) in &profile.codex {
        doc.insert(key.clone(), value.clone());
    }

    doc.insert("model_providers".to_string(), Value::Table(providers));
    doc
}

/// Render the document as TOML text.
pub fn render(doc: &Table) -> Result<String> {
    let header = "# Generated by llmx. Do not edit: rewritten on every launch.\n\
                  # Your own ~/.codex-local/config.toml is never modified.\n\n";
    let body = toml::to_string_pretty(doc)?;
    Ok(format!("{header}{body}"))
}

/// Write the document to `<generated_dir>/<profile id>.toml`.
pub fn write_generated(dir: &Path, profile_id: &str, doc: &Table) -> Result<PathBuf> {
    std::fs::create_dir_all(dir)?;
    let path = dir.join(format!("{profile_id}.toml"));
    std::fs::write(&path, render(doc)?)?;
    Ok(path)
}

/// Flatten the document into `key.path=<toml value>` strings for `-c`.
///
/// codex-local splits each override on the first `=`, parses the right-hand
/// side as TOML, and walks the left-hand side as a dotted path
/// (`common/src/config_override.rs`). Values are emitted in TOML form — a
/// quoted string stays a string, so a numeric-looking model id like `70b`
/// cannot be reinterpreted as an integer.
pub fn to_cli_overrides(doc: &Table) -> Result<Vec<String>> {
    let mut out = Vec::new();
    flatten(doc, &mut Vec::new(), &mut out)?;
    out.sort();
    Ok(out)
}

fn flatten(table: &Table, path: &mut Vec<String>, out: &mut Vec<String>) -> Result<()> {
    for (key, value) in table {
        // A dotted path cannot address a key that itself contains a dot.
        if key.contains('.') || key.contains('=') {
            return Err(anyhow!(
                "config key `{key}` contains `.` or `=`, which cannot be expressed as a \
                 codex-local `-c` override.\n\
                 Set `settings.isolation = \"codex_home\"` to pass the generated file directly \
                 instead."
            ));
        }
        path.push(key.clone());
        match value {
            Value::Table(nested) => flatten(nested, path, out)?,
            leaf => out.push(format!("{}={}", path.join("."), leaf)),
        }
        path.pop();
    }
    Ok(())
}
